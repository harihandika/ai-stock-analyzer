"""Metadata for persisted runs; SQLite CURRENT_TIMESTAMP values are UTC.

BacktestRun.created_at is generated by the database, never accepted from the
client. SQLite drops tzinfo on read; PostgreSQL returns an aware instant. This
normalizes that known writer contract without changing stored rows or session dates.
"""

from app.services.market_metadata import as_utc


def run_metadata(run):
    return {
        "run_id": str(run.id),
        "ticker": run.ticker,
        "created_at": as_utc(run.created_at),
        "data_revision": run.data_revision,
    }


def run_payload(run):
    return {**run.result, **run_metadata(run)}
